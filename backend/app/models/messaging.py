"""
Messaging models — structured threads tied to patients.

Tables:
  threads               — the conversation container
  thread_participants   — who is in each thread
  messages              — individual messages
  message_attachments   — files attached to a message (1-to-many)

Design notes:
  - Threads are NOT free-form DMs. Every thread has a "kind" (case,
    appointment, referral, broadcast, general) and an optional patient_id.
    The allowed-pairs matrix in core/allowed_threads.py enforces who can
    be in a thread together.
  - Participants are stored as rows so we can support group threads
    (e.g., "care team" with doctor + nurse + patient).
  - `client_message_id` (UUID generated by the sender) lets the client
    match optimistic UI sends with the server's authoritative message.
  - `last_message_at` on Thread is denormalized for fast "most recent
    first" sorting without a JOIN.
  - "Read" status is per-participant (stored on the participant row)
    because it's a per-user fact, not a per-message fact.
"""

import enum
import uuid
from datetime import datetime

from sqlalchemy import (
    Boolean,
    DateTime,
    Enum as SAEnum,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base


# ============================================================
# Enums
# ============================================================

class ThreadKind(str, enum.Enum):
    """The category of conversation. Determines allowed-pairs rules."""
    CASE = "case"                 # tied to a patient case (patient_id required)
    APPOINTMENT = "appointment"   # about a booking
    REFERRAL = "referral"         # doctor-to-doctor about a patient
    BROADCAST = "broadcast"       # admin announcement
    GENERAL = "general"           # e.g., staff-only coordination


# ============================================================
# Thread
# ============================================================

class Thread(Base):
    __tablename__ = "threads"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4,
    )

    kind: Mapped[ThreadKind] = mapped_column(
        SAEnum(ThreadKind, name="thread_kind",
               values_callable=lambda e: [m.value for m in e]),
        nullable=False, default=ThreadKind.GENERAL, index=True,
    )

    subject: Mapped[str] = mapped_column(String(300), nullable=False)

    # Optional patient this thread is about.
    patient_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True, index=True,
    )

    # Who created the thread (for audit).
    created_by_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="RESTRICT"),
        nullable=False,
    )

    # Denormalized for fast sorting.
    last_message_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(), index=True,
    )

    is_seed_data: Mapped[bool] = mapped_column(nullable=False, default=False, index=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now(),
    )

    participants = relationship(
        "ThreadParticipant",
        back_populates="thread",
        cascade="all, delete-orphan",
        lazy="selectin",
    )
    messages = relationship(
        "Message",
        back_populates="thread",
        cascade="all, delete-orphan",
        order_by="Message.created_at",
    )
    patient = relationship("User", foreign_keys=[patient_id], lazy="selectin")
    created_by = relationship("User", foreign_keys=[created_by_id], lazy="selectin")

    def __repr__(self) -> str:
        return f"<Thread {self.id} kind={self.kind.value} subject={self.subject!r}>"


# ============================================================
# Thread participant
# ============================================================

class ThreadParticipant(Base):
    __tablename__ = "thread_participants"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4,
    )
    thread_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("threads.id", ondelete="CASCADE"),
        nullable=False, index=True,
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False, index=True,
    )

    joined_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(),
    )
    last_read_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    thread = relationship("Thread", back_populates="participants")
    user = relationship("User", lazy="selectin")

    __table_args__ = (
        UniqueConstraint("thread_id", "user_id", name="uq_thread_participants_thread_user"),
    )

    def __repr__(self) -> str:
        return f"<ThreadParticipant thread={self.thread_id} user={self.user_id}>"


# ============================================================
# Message
# ============================================================

class Message(Base):
    __tablename__ = "messages"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4,
    )
    thread_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("threads.id", ondelete="CASCADE"),
        nullable=False, index=True,
    )
    sender_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="RESTRICT"),
        nullable=False, index=True,
    )

    body: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Client-generated ID for optimistic UI + retry deduplication.
    # Unique per (thread_id, client_message_id) — enforced by index.
    client_message_id: Mapped[str | None] = mapped_column(String(64), nullable=True)

    is_system: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=False,
        doc="True for system-generated messages (e.g. 'video call started')",
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(), index=True,
    )

    thread = relationship("Thread", back_populates="messages")
    sender = relationship("User", lazy="selectin")
    attachments = relationship(
        "MessageAttachment",
        back_populates="message",
        cascade="all, delete-orphan",
        lazy="selectin",
    )

    __table_args__ = (
        # Ensure a given sender can't double-insert the same client_message_id
        # into the same thread.
        UniqueConstraint(
            "thread_id", "sender_id", "client_message_id",
            name="uq_messages_thread_sender_client_id",
        ),
        Index("ix_messages_thread_created", "thread_id", "created_at"),
    )

    def __repr__(self) -> str:
        return f"<Message {self.id} thread={self.thread_id} sender={self.sender_id}>"


# ============================================================
# Attachment
# ============================================================

class MessageAttachment(Base):
    __tablename__ = "message_attachments"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4,
    )
    message_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("messages.id", ondelete="CASCADE"),
        nullable=True, index=True,
        doc="NULL until bound to a message (uploads happen before send)",
    )

    # Relative URL under /uploads/, e.g. "/uploads/chat/2026/10/abc123.pdf"
    url: Mapped[str] = mapped_column(String(500), nullable=False)

    # Original filename as uploaded by the user.
    filename: Mapped[str] = mapped_column(String(300), nullable=False)

    # MIME type — helps the client choose a renderer.
    content_type: Mapped[str] = mapped_column(String(100), nullable=False)

    size_bytes: Mapped[int] = mapped_column(Integer, nullable=False)

    # Optional: image dimensions, video duration — reserved for future use.
    width: Mapped[int | None] = mapped_column(Integer, nullable=True)
    height: Mapped[int | None] = mapped_column(Integer, nullable=True)
    duration_seconds: Mapped[int | None] = mapped_column(Integer, nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(),
    )

    message = relationship("Message", back_populates="attachments")

    def __repr__(self) -> str:
        return f"<MessageAttachment {self.filename} ({self.content_type})>"
