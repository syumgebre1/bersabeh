"""
SQLAlchemy declarative base.

Every ORM model in app/models/ inherits from `Base`. Alembic reads
`Base.metadata` to autogenerate migrations, so as long as a model is
imported somewhere before Alembic runs, its table shows up in migrations.

Why a separate file?
  - Models import Base from here.
  - Alembic imports Base from here.
  - The app imports models elsewhere (e.g. in main.py).
  This separation prevents circular imports.

Naming convention:
  We enforce a deterministic naming convention on all indexes, constraints,
  and foreign keys. This makes Alembic migrations stable across machines —
  without it, autogenerated constraint names can differ between developers.
"""

from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase


# ------------------------------------------------------------
# Deterministic naming convention for constraints and indexes.
# Without this, SQLite/Postgres may pick arbitrary names for
# constraints, which makes migrations non-reproducible.
# ------------------------------------------------------------
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """
    Base class for all ORM models.

    Subclass like:
        class User(Base):
            __tablename__ = "users"
            ...
    """

    metadata = MetaData(naming_convention=NAMING_CONVENTION)
